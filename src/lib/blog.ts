export function getPosts(category?: PostCategory): Post[] {
  // Найновіші зверху; опційно фільтр за категорією (blog | news).
  return [...POSTS]
    .filter((p) => !category || p.category === category)
    .sort((a, b) => (a.date < b.date ? 1 : -1));
}

/** Статті для блоку «Читайте також» на сторінці продукту. */
export function getPostsForProduct(product: string, limit = 3): Post[] {
  return getPosts("blog").filter((p) => p.product === product).slice(0, limit);
}

export function getPost(slug: string): Post | null {
  return POSTS.find((p) => p.slug === slug) ?? null;
}

export function formatPostDate(date: string): string {
  const [y, m, d] = date.split("-").map(Number);
  if (!y || !m || !d) return date;
  const months = ["січня", "лютого", "березня", "квітня", "травня", "червня", "липня", "серпня", "вересня", "жовтня", "листопада", "грудня"];
  return `${d} ${months[m - 1]} ${y}`;
}
